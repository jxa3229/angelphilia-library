import { expect, test } from '@playwright/test'

test('shares full-size originals and black variants with working copy and download links', async ({ page, context, baseURL }) => {
  const assetBase = new URL('./', baseURL).href
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  for (const id of ['doll-heads', 'bunny-outfits']) {
    await page.goto(`./#/image/${id}`)
    const image = page.locator('.image-frame img')
    await expect(image).toBeVisible()
    await expect.poll(() => image.evaluate((element) => [element.naturalWidth, element.naturalHeight])).toEqual([1800, 2400])
    await expect(page.getByRole('link', { name: '原图', exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(page.getByRole('link', { name: '下载 PNG' })).toHaveAttribute('download', `${id}.png`)
    await page.getByRole('button', { name: '复制图片直链', exact: true }).click()
    await expect(page.locator('.image-feedback')).toHaveText('链接已复制')
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(`${assetBase}images/${id}.png`)
    await page.getByRole('button', { name: '复制分享页链接', exact: true }).click()
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(`${assetBase}#/image/${id}`)
    await page.getByRole('link', { name: '黑底版', exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`#\/image\/${id}-dark$`))
    await expect(image).toHaveAttribute('src', new RegExp(`/images/${id}-dark.png$`))
    await expect.poll(() => image.evaluate((element) => element.complete && element.naturalWidth)).toBe(1800)
    await page.reload()
    await expect(page.getByRole('link', { name: '黑底版', exact: true })).toHaveAttribute('aria-current', 'page')
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  }
  expect(errors).toEqual([])
})

test('keeps collage links in the hidden panel and preserves backgrounds and language switching', async ({ page }) => {
  await page.goto('./#/overview')
  await expect(page.locator('.overview-images')).toHaveCount(0)
  await expect(page.locator('.personal-image-tools')).toHaveCount(0)
  await expect(page.locator('.main-panel a[href*="/image/"]')).toHaveCount(0)
  const backgrounds = await page.locator('.overview-masthead > div').evaluateAll((elements) => elements.map((element) => getComputedStyle(element, '::before').backgroundImage))
  expect(backgrounds[0]).toContain('/images/doll-heads-dark.webp')
  expect(backgrounds[1]).toContain('/images/bunny-outfits-dark.webp')
  await page.keyboard.type('000')
  await expect(page.locator('.purchase-links-dialog')).toBeVisible()
  await expect(page.locator('.personal-image-tools a')).toHaveCount(2)
  await page.locator('.personal-image-tools a').first().click()
  await expect(page).toHaveURL(/#\/image\/doll-heads$/)
  await expect(page.locator('.purchase-links-dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'English', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Doll portraits · 35 faces' })).toBeVisible()
  await page.getByRole('button', { name: '日本語', exact: true }).click()
  await expect(page.getByRole('link', { name: '黒背景版', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '黒背景版', exact: true }).click()
  await page.locator('.theme-row button').nth(1).click()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('handles missing images, loading failures, retry and denied clipboard access', async ({ page }) => {
  await page.goto('./#/image/unknown')
  await expect(page.getByRole('heading', { name: '没有找到这张图片' })).toBeVisible()
  await page.getByRole('link', { name: /返回图书馆速览/ }).click()
  await expect(page).toHaveURL(/#\/overview$/)
  await page.route('**/images/doll-heads.png', (route) => route.abort())
  await page.goto('./#/image/doll-heads')
  await expect(page.getByRole('alert')).toContainText('图片加载失败')
  await page.unroute('**/images/doll-heads.png')
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect.poll(() => page.locator('.image-frame img').evaluate((element) => element.naturalWidth)).toBe(1800)
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => Promise.reject(new Error('Denied')) } }))
  await page.getByRole('button', { name: '复制图片直链', exact: true }).click()
  await expect(page.locator('.image-feedback')).toContainText('复制失败')
  await expect(page.locator('.image-links a').first()).toHaveAttribute('href', /\/images\/doll-heads.png$/)
})
