test('browses the collapsed brand directory and preserves it when returning from details', async ({ page }) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.getByRole('link', { name: /馆藏条目/ }).click()
  const roster = page.locator('.doll-roster')
  await expect(roster).not.toHaveAttribute('open')
  await roster.locator(':scope > summary').click()
  await expect(roster.locator('.roster-group')).toHaveCount(4)
  const vmf = roster.locator('[data-brand="vmf"]')
  await vmf.locator(':scope > summary').click()
  const miu = vmf.locator('[data-entry="vmf-1"]')
  await expect(miu).toContainText('美雨 · MIU')
  await miu.locator('summary').click()
  await expect(miu.locator('button')).toHaveCount(3)
  await page.getByPlaceholder(/搜索名字/).fill('not-in-the-collection')
  await miu.locator('button').first().click()
  await expect(page.locator('.detail-page')).toBeVisible()
  await expect(page.locator('.record-metadata')).toContainText('VMF50')
  await expect(roster).toBeHidden()
  await page.getByRole('button', { name: /返回馆藏条目/ }).click()
  await expect(roster).toHaveAttribute('open', '')
  await expect(miu.locator('button').first()).toBeVisible()
  await expect(page.getByPlaceholder(/搜索名字/)).toHaveValue('not-in-the-collection')
  const pd = roster.locator('[data-brand="pinkdrops"]')
  await pd.locator(':scope > summary').click()
  await expect(pd.locator('[data-entry="pinkdrops-41"]')).toContainText('名称待补充')
  await expect(pd.locator('[data-entry="pinkdrops-41"] button')).toHaveCount(0)
  await expect(pd.locator('[data-entry="pinkdrops-22"]')).toContainText('暂无匹配馆藏')
  await page.getByRole('button', { name: 'English', exact: true }).click()
  await expect(roster.locator('.roster-heading')).toContainText('Doll number & name directory')
  await expect(pd.locator('[data-entry="pinkdrops-22"]')).toContainText('No matching record')
  await page.getByRole('button', { name: '日本語', exact: true }).click()
  await expect(roster.locator('.roster-heading')).toContainText('品番・キャラクター名一覧')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(pd.locator('[data-entry="pinkdrops-84"]')).toContainText('美久')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  expect(errors).toEqual([])
})

